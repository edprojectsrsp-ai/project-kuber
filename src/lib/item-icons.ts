export function resolveItemIcon(name = '', icon = 'auto'): ItemIconKey {
  // Earlier catalogues stored the general safety icon for every shoe size.
  if (icon === 'safety' && /shoe|boot|footwear/i.test(name)) return 'shoe';
  if (icon !== 'auto' && Object.hasOwn(ICON_STYLES, icon)) return icon as ItemIconKey;
  return rules.find(([pattern]) => pattern.test(name))?.[1] || 'package';
}
